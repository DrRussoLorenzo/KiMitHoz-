  const nyelvek = { hu: 'hu-HU', en: 'en-US', de: 'de-DE' };
  const alapSzoveg = new WeakMap();
  const utoljaraMegjelenitett = new WeakMap();
  const alapAttribútumok = new WeakMap();
  const utoljaraMegjelenitettAttribútumok = new WeakMap();
  let aktivNyelv = 'hu';
  const eredetiOldalcim = document.title;

  function forditas(szoveg, nyelv = aktivNyelv) {
    if (!nyelvek[nyelv] || nyelv === 'hu') return szoveg;
    if (szovegek[szoveg]?.[nyelv]) return szovegek[szoveg][nyelv];

    const emlites = szoveg.match(/^(.+?) megemlített a\(z\) (.+?) buli chatjében: (.*)$/s);
    if (emlites) {
      const [, felado, buli, uzenet] = emlites;
      return nyelv === 'en'
        ? `${felado} mentioned you in the ${buli} party chat: ${uzenet}`
        : `${felado} hat dich im Party-Chat von ${buli} erwähnt: ${uzenet}`;
    }

    const meghivo = szoveg.match(/^(.+?) meghívott erre: (.+)$/s);
    if (meghivo) {
      const [, felado, buli] = meghivo;
      return nyelv === 'en'
        ? `${felado} invited you to: ${buli}`
        : `${felado} hat dich eingeladen zu: ${buli}`;
    }

    const reszlegesForditasok = {
      ' Buli szervezése': { en: ' Create a party', de: ' Party erstellen' },
      'Kezdjük el': { en: 'Get started', de: 'Los geht’s' },
      ' kép': { en: ' photos', de: ' Bilder' },
      ' fő': { en: ' guests', de: ' Gäste' },
    };
    return Object.entries(reszlegesForditasok)
      .sort(([a], [b]) => b.length - a.length)
      .reduce((szovegResz, [magyar, forditott]) => {
        return szovegResz.split(magyar).join(forditott[nyelv]);
      }, szoveg);
  }

  function forditottSzovegCsomopont(csomopont) {
    const jelenlegi = csomopont.nodeValue;
    const korabbi = utoljaraMegjelenitett.get(csomopont);
    let eredeti = alapSzoveg.get(csomopont);
    if (!eredeti || jelenlegi !== korabbi) {
      const eleje = jelenlegi.match(/^\s*/)?.[0] || '';
      const vege = jelenlegi.match(/\s*$/)?.[0] || '';
      eredeti = { eleje, vege, szoveg: jelenlegi.trim() };
      alapSzoveg.set(csomopont, eredeti);
    }
    let forditott = forditas(eredeti.szoveg);
    if (aktivNyelv !== 'hu' && forditott === eredeti.szoveg) {
      const elotag = Object.keys(szovegek).find(
        (kulcs) => kulcs.endsWith(',') && eredeti.szoveg.startsWith(`${kulcs} `)
      );
      if (elotag)
        forditott = `${szovegek[elotag][aktivNyelv]}${eredeti.szoveg.slice(elotag.length)}`;
    }
    const ujSzoveg = `${eredeti.eleje}${forditott}${eredeti.vege}`;
    utoljaraMegjelenitett.set(csomopont, ujSzoveg);
    if (jelenlegi !== ujSzoveg) csomopont.nodeValue = ujSzoveg;
  }

  function forditottAttribútum(elem, nev) {
    const jelenlegi = elem.getAttribute(nev);
    if (!jelenlegi) return;
    let eredetiElem = alapAttribútumok.get(elem);
    let megjelenitettElem = utoljaraMegjelenitettAttribútumok.get(elem);
    if (!eredetiElem) {
      eredetiElem = new Map();
      megjelenitettElem = new Map();
      alapAttribútumok.set(elem, eredetiElem);
      utoljaraMegjelenitettAttribútumok.set(elem, megjelenitettElem);
    }
    if (!eredetiElem.has(nev) || jelenlegi !== megjelenitettElem.get(nev)) {
      eredetiElem.set(nev, jelenlegi);
    }
    const ujErtek = forditas(eredetiElem.get(nev));
    megjelenitettElem.set(nev, ujErtek);
    if (jelenlegi !== ujErtek) elem.setAttribute(nev, ujErtek);
  }

  function forditottElem(elem) {
    if (elem.nodeType === Node.TEXT_NODE) {
      if (elem.nodeValue.trim()) forditottSzovegCsomopont(elem);
      return;
    }
    if (elem.nodeType !== Node.ELEMENT_NODE && elem.nodeType !== Node.DOCUMENT_NODE) return;

    function attribútumokForditasa(elem) {
      for (const nev of ['aria-label', 'placeholder', 'title', 'alt'])
        forditottAttribútum(elem, nev);
    }
    if (elem.nodeType === Node.ELEMENT_NODE) attribútumokForditasa(elem);
    const elemek = document.createTreeWalker(elem, NodeFilter.SHOW_ELEMENT);
    while (elemek.nextNode()) attribútumokForditasa(elemek.currentNode);
    const jaras = document.createTreeWalker(elem, NodeFilter.SHOW_TEXT);
    while (jaras.nextNode()) forditottSzovegCsomopont(jaras.currentNode);
  }

  function nyelvBeallitasa(nyelv = 'hu') {
    aktivNyelv = Object.prototype.hasOwnProperty.call(nyelvek, nyelv) ? nyelv : 'hu';
    document.documentElement.lang = aktivNyelv;
    document.title = forditas(eredetiOldalcim);
    forditottElem(document.body);
  }

  const figyelo = new MutationObserver((valtozasok) => {
    for (const valtozas of valtozasok) {
      if (valtozas.type === 'characterData') forditottSzovegCsomopont(valtozas.target);
      for (const csomopont of valtozas.addedNodes || []) forditottElem(csomopont);
      if (valtozas.type === 'attributes')
        forditottAttribútum(valtozas.target, valtozas.attributeName);
    }
  });
  figyelo.observe(document.documentElement, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['aria-label', 'placeholder', 'title', 'alt'],
  });

  window.KiMitHozI18n = {
    forditas,
    nyelvBeallitasa,
    aktivNyelv: () => aktivNyelv,
    locale: () => nyelvek[aktivNyelv],
  };
